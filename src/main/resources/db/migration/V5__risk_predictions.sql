-- Synaptech AI Platform: Multi-Metric Project Telemetry, Risk Predictions, and TreeSHAP Attributions Schema

CREATE TABLE IF NOT EXISTS project_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR(36),
    project_id BIGINT NOT NULL,
    defect_arrival_rate DOUBLE PRECISION DEFAULT 0.0,
    sprint_velocity_variance DOUBLE PRECISION DEFAULT 0.0,
    technical_debt_ratio DOUBLE PRECISION DEFAULT 0.0,
    code_quality_index DOUBLE PRECISION DEFAULT 75.0,
    requirement_churn DOUBLE PRECISION DEFAULT 0.0,
    sprint_velocity INTEGER DEFAULT 30,
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_metric_project FOREIGN KEY (project_id) REFERENCES project(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_metric_project_time ON project_metrics(project_id, recorded_at DESC);

CREATE TABLE IF NOT EXISTS project_risk_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR(36),
    project_id BIGINT NOT NULL,
    metric_snapshot_id BIGINT,
    defect_risk DOUBLE PRECISION DEFAULT 0.0,
    agile_risk DOUBLE PRECISION DEFAULT 0.0,
    overall_risk_score DOUBLE PRECISION NOT NULL,
    risk_band VARCHAR(20) DEFAULT 'LOW',
    confidence_lower DOUBLE PRECISION DEFAULT 0.0,
    confidence_upper DOUBLE PRECISION DEFAULT 100.0,
    model_version VARCHAR(50) DEFAULT 'risk-lightgbm-v1.0',
    predicted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pred_project FOREIGN KEY (project_id) REFERENCES project(id) ON DELETE CASCADE,
    CONSTRAINT fk_pred_metric FOREIGN KEY (metric_snapshot_id) REFERENCES project_metrics(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_pred_project_time ON project_risk_predictions(project_id, predicted_at DESC);

CREATE TABLE IF NOT EXISTS risk_explanations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_prediction_id BIGINT NOT NULL,
    feature_name VARCHAR(100) NOT NULL,
    raw_value DOUBLE PRECISION DEFAULT 0.0,
    shap_value DOUBLE PRECISION NOT NULL,
    direction VARCHAR(20) NOT NULL,
    recommendation TEXT,
    CONSTRAINT fk_exp_prediction FOREIGN KEY (risk_prediction_id) REFERENCES project_risk_predictions(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_exp_prediction ON risk_explanations(risk_prediction_id);

CREATE TABLE IF NOT EXISTS project_health (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT,
    risk_score INTEGER,
    bug_trend VARCHAR(255),
    sprint_velocity INTEGER,
    technical_debt VARCHAR(255),
    code_quality_index INTEGER,
    team_productivity VARCHAR(255),
    project_progress INTEGER,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_health_project FOREIGN KEY (project_id) REFERENCES project(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_health_project_time ON project_health(project_id, timestamp DESC);

